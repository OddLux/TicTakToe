def replace_once(text, old, new, label):
    """Replace exactly one occurrence of old, or fail loudly."""
    count = text.count(old)
    if count != 1:
        raise SystemExit(f"{label}: expected 1 match, found {count}: {old[:60]!r}")
    return text.replace(old, new)


def replace_all(text, old, new, label):
    """Replace every occurrence of old; fail if there is none."""
    if old not in text:
        raise SystemExit(f"{label}: no match for {old!r}")
    return text.replace(old, new)


def read(name):
    """Read a plugin/ file with normalized newlines."""
    return (PLUGIN_DIR / name).read_text(encoding="utf-8")


def write(name, text):
    """Write a plugin/ file with LF newlines."""
    (PLUGIN_DIR / name).write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {PLUGIN_DIR / name}")


def build_lua(var):
    """Return the Mac plugin source for one variant."""
    label = var["target"] + ".lua"
    text = read(var["source"] + ".lua")
    text = replace_once(text, PATH_BLOCK_OLD, "", label)
    text = replace_once(text, DIR_FN_OLD, DIR_FN_NEW, label)
    text = replace_once(text, FIND_OLD, FIND_NEW, label)
    text = replace_once(text, FIND_ANCHOR, FIND_LIB_FN + FIND_ANCHOR, label)
    for old, new in var["names"]:
        text = replace_all(text, old, new, label)
    first_line, rest = text.split("\n", 1)
    first_line = first_line.replace(var["source"] + ".lua", label) + " (macOS)"
    header = MAC_HEADER.format(source=var["source"] + ".lua")
    return first_line + "\n--\n" + header + rest


def build_xml(var):
    """Return the Mac Plugins-pool wrapper for one variant."""
    label = var["target"] + ".xml"
    text = read(var["source"] + ".xml")
    text = replace_once(text, var["guid"][0], var["guid"][1], label)
    text = re.sub(
        r'(Plugin Name|ComponentLua Name="Main" FileName)="' + var["source"],
        r'\1="' + var["target"],
        text,
    )
    text = replace_all(text, var["source"] + ".xml --", label + " --", label)
    return text


def build_test(var):
    """Return the Mac test for one variant: the Windows test, retargeted."""
    src_test, dst_test = var["test"]
    text = read(src_test)
    text = replace_once(text, WIN_LIB, TEST_LIB_NEW, dst_test)
    text = replace_all(
        text,
        f'"plugin/{var["source"]}.lua"',
        f'"plugin/{var["target"]}.lua"',
        dst_test,
    )
    text = replace_all(
        text,
        f"cannot open plugin/{var['source']}.lua",
        f"cannot open plugin/{var['target']}.lua",
        dst_test,
    )
    for old, new in var["names"] + var.get("test_names", []):
        if old in text:
            text = text.replace(old, new)
    text = replace_once(
        text, var["test_anchor"], TEST_TAIL + var["test_anchor"], dst_test
    )
    header = (
        f"-- GENERATED by scripts/make_mac_variants.py from {src_test}: the same\n"
        f"-- suite run against plugin/{var['target']}.lua with a mocked macOS\n"
        "-- GetPath(). Do not edit by hand.\n--\n"
    )
    return header + text


def main():
    """Regenerate every Mac plugin, wrapper, and test."""
    for var in VARIANTS:
        write(var["target"] + ".lua", build_lua(var))
        write(var["target"] + ".xml", build_xml(var))
        write(var["test"][1], build_test(var))


if __name__ == "__main__":
    main()
